LANGS = ("en", "ru")
_lang = "en"


def set_lang(lang):
    global _lang
    _lang = lang if lang in STRINGS else "en"


def get_lang():
    return _lang


def t(key, **kw):
    s = STRINGS[_lang].get(key) or STRINGS["en"].get(key) or key
    if kw:
        try:
            return s.format(**kw)
        except (KeyError, ValueError, IndexError):
            return s
    return s


def log_line(key, **p):
    """Format an engine log event into the current language."""
    if key == "log_source" and p.get("out_fps"):
        key = "log_source_fps"
    if "mode" in p:
        p["mode"] = t("mode_" + p["mode"])
    if "keep" in p:
        p["keep"] = t("keep_suffix", keep=p["keep"]) if p["keep"] > 1 else ""
    return t(key, **p)
